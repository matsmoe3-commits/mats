export function applySeed() {
  const done = store.setting('seeded', []);
  const todo = SEED.filter((s) => !done.includes(s.id));
  if (!todo.length) return;
  store.upsertMany('ideas', todo);
  store.setSetting('seeded', [...done, ...todo.map((s) => s.id)]);
}
